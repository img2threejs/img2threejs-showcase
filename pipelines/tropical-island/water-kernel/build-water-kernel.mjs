#!/usr/bin/env node
// Offline regeneration only; npm build uses the committed TypeScript payload.
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const sources = ['water-kernel.c', 'water-step.c', 'water-foam.c'].map(name => join(here, name));
const output = resolve(here, '../../../src/demos/tropical-island/waterKernelCode.ts');
const homebrewClang = '/opt/homebrew/opt/llvm/bin/clang';
const clang = process.env.CLANG || (existsSync(homebrewClang) ? homebrewClang : 'clang');
const directory = mkdtempSync(join(tmpdir(), 'island-water-kernel-'));
const wasm = join(directory, 'kernel.wasm');
const exports = [
  'update_velocities', 'compute_stage', 'bed_address', 'depth_address',
  'momentum_x_address', 'momentum_z_address', 'velocity_x_address', 'velocity_z_address',
  'axis_address', 'cell_widths_address', 'grid_size', 'failure_h',
  'cfl_signal', 'snapshot_state', 'blend_state', 'prepare_foam_sources', 'update_foam',
  'foam_address', 'wetness_address', 'foam_offset_x_address', 'foam_offset_z_address',
  'shore_normal_x_address', 'shore_normal_z_address', 'shore_impulse_x_address', 'shore_impulse_z_address',
  'foam_candidates_address', 'foam_compression_address', 'foam_source_step_address',
];

try {
  const result = spawnSync(clang, [
    '--target=wasm32-unknown-unknown', '-O3', '-msimd128', '-nostdlib', '-ffreestanding', '-fno-builtin',
    '-ffp-contract=off', '-fno-fast-math', '-fno-trapping-math',
    '-Wl,--no-entry', '-Wl,--strip-debug', '-Wl,--export-memory',
    ...exports.map(name => `-Wl,--export=${name}`), '-o', wasm, ...sources,
  ], { stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`Water kernel compiler exited ${result.status}; set CLANG to LLVM clang with wasm-ld`);
  const bytes = readFileSync(wasm);
  writeFileSync(output, `// Generated by pipelines/tropical-island/water-kernel/build-water-kernel.mjs\n// Strict float64; no fast-math, reassociation or FMA.\nexport default '${bytes.toString('base64')}';\n`);
  console.log(`Water kernel: ${bytes.length} wasm bytes encoded in waterKernelCode.ts`);
} finally {
  rmSync(directory, { recursive: true, force: true });
}
