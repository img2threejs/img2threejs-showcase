#!/usr/bin/env node
// Scaffolds a new showcase demo: creates src/demos/<id>/, a stub factory,
// and inserts metadata plus a literal lazy runtime loader into the authored catalog.
// Plain Node, no deps.
//
// Usage:
//   npm run new-demo -- <id> "<Title>" [object|character]
//
// Example:
//   npm run new-demo -- rubber-duck "Rubber Duck" object

import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

function fail(message) {
  console.error(`\nnew-showcase: ${message}\n`);
  process.exit(1);
}

function toPascalCase(id) {
  return id
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function singleQuoted(value) {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/[\r\n]+/g, ' ');
}

function occurrenceCount(source, needle) {
  return source.split(needle).length - 1;
}

function main() {
  const [id, title, subjectClassArg] = process.argv.slice(2);

  if (!id) {
    fail('missing <id>. Usage: npm run new-demo -- <id> "<Title>" [object|character]');
  }
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(id)) {
    fail(`"${id}" is not kebab-case (lowercase letters, digits, hyphens only).`);
  }
  if (subjectClassArg && subjectClassArg !== 'object' && subjectClassArg !== 'character') {
    fail(`"${subjectClassArg}" is not a subject class. Use "object" or "character".`);
  }

  const subjectClass = subjectClassArg ?? 'object';
  const displayTitle = title || toPascalCase(id).replace(/([a-z])([A-Z])/g, '$1 $2');
  const pascalId = toPascalCase(id);
  const factoryFnName = `create${pascalId}Model`;
  const demoDir = join(ROOT, 'src/demos', id);
  const factoryFile = join(demoDir, `${factoryFnName}.ts`);
  const registryFile = join(ROOT, 'src/demos/registry.ts');

  if (existsSync(demoDir)) {
    fail(`src/demos/${id}/ already exists — pick a different id, or edit it directly.`);
  }
  if (!existsSync(registryFile)) {
    fail(`could not find ${registryFile} — run this from the repo root.`);
  }

  const registrySource = readFileSync(registryFile, 'utf8');
  if (new RegExp(`id:\\s*'${id}'`).test(registrySource)) {
    fail(`registry.ts already has an entry with id "${id}".`);
  }

  // The generated block depends on these catalog contracts. Validate every anchor before making
  // the demo directory so a registry refactor can never leave a half-created contribution behind.
  const newline = registrySource.includes('\r\n') ? '\r\n' : '\n';
  const authoredAnchor = `const authored: CatalogEntry[] = [${newline}`;
  const requiredAnchors = [
    ['CatalogEntry declaration', 'type CatalogEntry = DemoMetadata & {'],
    ['CatalogEntry runtime loader', 'loadRuntime: () => Promise<DemoRuntime>;'],
    ['BASE metadata constant', 'const BASE = import.meta.env.BASE_URL;'],
    ['REPO metadata constant', "const REPO = 'https://github.com/img2threejs/img2threejs-showcase/blob/main';"],
    ['authored catalog', authoredAnchor],
  ];
  for (const [label, anchor] of requiredAnchors) {
    const count = occurrenceCount(registrySource, anchor);
    if (count !== 1) {
      fail(`expected exactly one ${label} anchor in registry.ts, found ${count}; update the scaffold before retrying.`);
    }
  }

  const factorySource = `import * as THREE from 'three';

// TODO: replace this placeholder with the factory generated by img2threejs.
// Keep the exported function name (${factoryFnName}) so the registry's lazy loader
// keeps working, or update both if you rename it.
export function ${factoryFnName}(): THREE.Group {
  const group = new THREE.Group();
  group.name = '${id}';
  const mesh = new THREE.Mesh(
    new THREE.BoxGeometry(1, 1, 1),
    new THREE.MeshStandardMaterial({ color: 0x888888, roughness: 0.6 }),
  );
  mesh.name = '${id}-mesh';
  mesh.castShadow = true;
  group.add(mesh);
  // Full-assembly export is inherited automatically from the shared demo viewer. If this showcase
  // contains multiple independent models, declare only those model roots here:
  // group.userData.exportModels = [{ id: 'model-a', label: 'Model A', root: modelA }];
  return group;
}
`;

  const entryBlock = `  {
    id: '${id}',
    updatedAt: '${new Date().toISOString().slice(0, 10)}',
    title: '${singleQuoted(displayTitle)}',
    subjectClass: '${subjectClass}',
    blurb:
      'TODO: 1-2 sentences describing what makes this reconstruction interesting.',
    referenceImage: \`\${BASE}references/${id}.png\`,
    sourcePath: 'src/demos/${id}/${factoryFnName}.ts',
    sourceUrl: \`\${REPO}/src/demos/${id}/${factoryFnName}.ts\`,
    generatedWith: 'img2threejs vX.Y', // TODO: fill in the version you used
    author: 'TODO: your display name',
    authorUrl: 'TODO: https://github.com/your-username',
    status: 'placeholder', // set to 'final' once the real factory is in
    cameraPosition: [3, 2, 4],
    cameraTarget: [0, 0, 0],
    cameraFov: 35,
    loadRuntime: async () => {
      const { ${factoryFnName} } = await import('./${id}/${factoryFnName}');
      return {
        build: (scene) => {
          const group = ${factoryFnName}();
          scene.add(group);
          return group;
        },
      };
    },
  },
`;

  const updatedRegistry = registrySource.replace(
    authoredAnchor,
    `${authoredAnchor}${entryBlock.replaceAll('\n', newline)}`,
  );

  // Write the registry beside its destination and rename it only after the new factory exists.
  // Any write failure removes the directory this invocation created and leaves registry.ts intact.
  const registryTempFile = `${registryFile}.new-showcase-${process.pid}-${id}.tmp`;
  try {
    mkdirSync(demoDir, { recursive: false });
    writeFileSync(factoryFile, factorySource);
    writeFileSync(registryTempFile, updatedRegistry, { flag: 'wx' });
    renameSync(registryTempFile, registryFile);
  } catch (error) {
    rmSync(registryTempFile, { force: true });
    rmSync(demoDir, { recursive: true, force: true });
    const message = error instanceof Error ? error.message : String(error);
    fail(`could not write the scaffold: ${message}`);
  }

  console.log(`
Scaffolded "${id}":
  - src/demos/${id}/${factoryFnName}.ts       (placeholder box — replace with img2threejs output)
  - src/demos/registry.ts                      (metadata + lazy runtime loader added, marked TODO)

Next steps:
  1. Replace the placeholder factory body with your generated code.
  2. Fill in every TODO in the new registry.ts entry (blurb, generatedWith, author, authorUrl).
  3. Add public/references/${id}.png (or .jpg/.jpeg/.webp, <= 800 KB).
  4. Open #/demo/${id} and verify the inherited six-format export panel.
  5. If it contains multiple independent models, declare group.userData.exportModels roots.
  6. npm run build && npm run preview
  7. node scripts/qa-export-matrix.mjs --only=${id}
  8. node scripts/check-showcase-safety.mjs --base main
  9. git add -A && git commit -m "Add ${id} showcase demo" && git push
 10. gh pr create --fill   (or open https://github.com/hoainho/img2threejs-showcase/compare)
`);
}

main();
