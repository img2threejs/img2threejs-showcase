import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

// Recover the source UV/material channels discarded by the vertex-colour export.
// Existing geometry, vertex order, skin weights and animation data are not changed.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sources = process.argv.slice(2);
assert.equal(sources.length, 2, 'Usage: node scripts/restore-sora-materials.mjs skin-a-rig.glb skin-b-rig.glb');
const server = await createServer({ root, server: { middlewareMode: true }, appType: 'custom' });
try {
  const { decodeModel } = await server.ssrLoadModule('/src/demos/sora/meshCodec.ts');
  for (const [index, skin] of ['a', 'b'].entries()) {
    const bytes = readFileSync(sources[index]);
    assert.equal(bytes.toString('ascii', 0, 4), 'glTF');
    const jsonLength = bytes.readUInt32LE(12);
    const gltf = JSON.parse(bytes.toString('utf8', 20, 20 + jsonLength));
    const binary = bytes.subarray(28 + jsonLength);
    const accessor = (id) => {
      const a = gltf.accessors[id], v = gltf.bufferViews[a.bufferView];
      assert(!v.byteStride, 'Interleaved source accessors require explicit decoding');
      const Type = { 5126: Float32Array, 5125: Uint32Array, 5123: Uint16Array }[a.componentType];
      const width = { SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4 }[a.type];
      assert(Type && width && !a.sparse, 'Unsupported source accessor');
      const offset = (v.byteOffset ?? 0) + (a.byteOffset ?? 0);
      const data = binary.subarray(offset, offset + a.count * width * Type.BYTES_PER_ELEMENT);
      return new Type(data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength));
    };
    const { SURFACE_MODEL, SURFACE_STREAM } = await server.ssrLoadModule(`/src/demos/sora/surfaceData.skin-${skin}.ts`);
    const [surface] = decodeModel(SURFACE_MODEL, SURFACE_STREAM);
    const primitive = gltf.meshes[0].primitives[0];
    const position = accessor(primitive.attributes.POSITION);
    const indices = accessor(primitive.indices);
    const uv = accessor(primitive.attributes.TEXCOORD_0);
    assert.equal(indices.length, surface.index.length, 'Source topology differs');
    const mappedUv = new Float32Array(surface.position.length / 3 * 2);
    const assigned = new Uint8Array(surface.position.length / 3);
    let maxPositionError = 0;
    for (let corner = 0; corner < indices.length; corner++) {
      const source = indices[corner], target = surface.index[corner];
      for (let axis = 0; axis < 3; axis++) maxPositionError = Math.max(maxPositionError,
        Math.abs(position[source * 3 + axis] - surface.position[target * 3 + axis]));
      for (let axis = 0; axis < 2; axis++) {
        const value = uv[source * 2 + axis];
        assert(!assigned[target] || Math.abs(mappedUv[target * 2 + axis] - value) < 0.00001,
          `UV seam needs splitting at vertex ${target}`);
        mappedUv[target * 2 + axis] = value;
      }
      assigned[target] = 1;
    }
    assert(maxPositionError < 0.00002, `Source triangle order or positions differ: ${maxPositionError}`);
    assert(mappedUv.every(Number.isFinite), 'Invalid source UVs');
    const sourceHash = createHash('sha256').update(bytes).digest('hex');
    const folder = resolve(root, 'src/demos/sora/textures');
    mkdirSync(folder, { recursive: true });
    const material = gltf.materials[primitive.material];
    for (const [channel, texture] of [
      ['albedo', material.pbrMetallicRoughness.baseColorTexture],
      ['normal', material.normalTexture],
      ['orm', material.pbrMetallicRoughness.metallicRoughnessTexture],
    ]) {
      const image = gltf.images[gltf.textures[texture.index].source];
      assert.equal(image.mimeType, 'image/jpeg', 'Keep the original encoding; do not silently convert');
      const view = gltf.bufferViews[image.bufferView];
      writeFileSync(resolve(folder, `skin-${skin}-${channel}.jpg`), binary.subarray(view.byteOffset, view.byteOffset + view.byteLength));
    }
    writeFileSync(resolve(root, `src/demos/sora/surfaceUv.skin-${skin}.ts`),
      `// Original UVs; source GLB SHA256 ${sourceHash}. Generated by restore-sora-materials.mjs.\n`
      + `export const SURFACE_UV = '${Buffer.from(mappedUv.buffer, mappedUv.byteOffset, mappedUv.byteLength).toString('base64')}';\n`);
    console.log(JSON.stringify({ skin, vertices: position.length / 3, triangles: indices.length / 3, maxPositionError, sourceHash, restored: ['uv', 'albedo', 'normal', 'roughness', 'metalness'] }));
  }
} finally {
  await server.close();
}
